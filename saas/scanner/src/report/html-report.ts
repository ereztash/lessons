function clientScript(): string {
  // Tiny vanilla-JS sorter. Stored as a string so the HTML report is single-file.
  return `
(function(){
  var table = document.getElementById('repos-table');
  if (!table) return;
  var ths = table.querySelectorAll('thead th');
  ths.forEach(function(th, idx){
    th.addEventListener('click', function(){
      var type = th.getAttribute('data-sort') || 'string';
      var dir = th.classList.contains('sort-asc') ? 'desc' : 'asc';
      ths.forEach(function(o){ o.classList.remove('sort-asc','sort-desc'); });
      th.classList.add(dir === 'asc' ? 'sort-asc' : 'sort-desc');
      var tbody = table.querySelector('tbody');
      var rows = Array.prototype.slice.call(tbody.querySelectorAll('tr'));
      rows.sort(function(a,b){
        var av = a.children[idx].textContent.trim();
        var bv = b.children[idx].textContent.trim();
        if (type === 'number') {
          var an = parseFloat(av.replace(/[^0-9.\\-]/g,'')) || 0;
          var bn = parseFloat(bv.replace(/[^0-9.\\-]/g,'')) || 0;
          return dir === 'asc' ? an - bn : bn - an;
        }
        return dir === 'asc'
          ? av.localeCompare(bv)
          : bv.localeCompare(av);
      });
      rows.forEach(function(r){ tbody.appendChild(r); });
    });
  });
})();
`;
}

// ---------------------------------------------------------------------------
// escaping
// ---------------------------------------------------------------------------

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function escapeAttr(s: string): string {
  return escapeHtml(s);
}
